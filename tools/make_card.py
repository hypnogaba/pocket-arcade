"""Makes server/card.js: the picture X shows under a shared Pocket Arcade post (1200 x 630 PNG, base64).

  ~/Projects/forkbomb/.venv/bin/python tools/make_card.py
Built from build/tanks/sheet.png (cc ... tools/tank_test.c; build/tank_test build/tanks).
"""
import base64, io, os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet = Image.open(os.path.join(ROOT, "build/tanks/sheet.png")).convert("RGB")
title = sheet.crop((0, 0, 320, 288))
play = sheet.crop((656, 0, 976, 288))
W, H = 1200, 630
img = Image.new("RGB", (W, H), (14, 8, 30))
img.paste(title.resize((480, 432), Image.NEAREST), (70, 160))
img.paste(play.resize((480, 432), Image.NEAREST), (650, 160))
d = ImageDraw.Draw(img)
font = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
d.text((70, 24), "POCKET ARCADE", font=ImageFont.truetype(font, 64), fill=(255, 255, 255))
d.text((72, 104), "16 free Game Boy games and Tank Siege on the Solana Breakpoint badge", font=ImageFont.truetype(font, 28), fill=(181, 140, 255))
buf = io.BytesIO()
img.save(buf, "PNG", optimize=True)
os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
img.save(os.path.join(ROOT, "build/card.png"))
with open(os.path.join(ROOT, "server/card.js"), "w") as f:
    f.write("// Generated by tools/make_card.py: the X share picture, 1200 x 630 PNG.\n")
    f.write(f"export const CARD_B64 = '{base64.b64encode(buf.getvalue()).decode()}';\n")
print(len(buf.getvalue()), "bytes png")
